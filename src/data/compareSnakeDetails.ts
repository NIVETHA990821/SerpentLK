export function compareSnakeDetails(snake: Snake, language: CompareLanguage) {
  if (language === 'en') {
    return {
      danger: snake.venomLevel,
      venomType: snake.venomType,
      pattern: snake.pattern,
      keyFeatures: snake.keyFeatures,
      active: snake.activeTime,
      habitats: snake.habitats,
    };
  }
  const locale = language;
  const translated = details[snake.id]?.[locale];
  const venom = venomLabels[snake.venomType];
  const danger = dangerLabels[snake.venomLevel as keyof typeof dangerLabels];
  const active = activityLabels[snake.activeTime as keyof typeof activityLabels];
  return {
    danger: danger?.[locale] ?? snake.venomLevel,
    venomType: venom?.[locale] ?? snake.venomType,
    pattern: translated?.pattern ?? snake.pattern,
    keyFeatures: translated?.keyFeatures ?? snake.keyFeatures,
    active: active?.[locale] ?? snake.activeTime,
    habitats: snake.habitats.map(h => habitatLabels[h]?.[locale] ?? h),
  };
}
